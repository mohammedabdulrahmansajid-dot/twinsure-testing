-- Stores the AI Twin risk configuration captured when a policy is issued.
-- The snapshot remains unchanged even if the current Twin later changes.

CREATE TABLE IF NOT EXISTS POLICY_TWIN_SNAPSHOTS (
                                                     snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                     policy_id BIGINT NOT NULL UNIQUE,
                                                     twin_id BIGINT NOT NULL,
                                                     twin_name VARCHAR(100) NOT NULL,
    autonomy_level VARCHAR(50) NOT NULL,
    transaction_limit DECIMAL(12, 2) NOT NULL,
    approval_threshold DECIMAL(12, 2) NOT NULL,
    twin_status VARCHAR(50) NOT NULL,
    captured_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_policy_twin_snapshot
    FOREIGN KEY (policy_id)
    REFERENCES POLICIES(policy_id)
    ON DELETE CASCADE
    );

-- Stores the action permissions captured together with the Twin snapshot.

CREATE TABLE IF NOT EXISTS POLICY_PERMISSION_SNAPSHOTS (
                                                           permission_snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                           policy_id BIGINT NOT NULL,
                                                           action_type VARCHAR(50) NOT NULL,
    permission_level VARCHAR(50) NOT NULL,
    action_limit DECIMAL(12, 2),
    active BOOLEAN NOT NULL,

    CONSTRAINT fk_policy_permission_snapshot
    FOREIGN KEY (policy_id)
    REFERENCES POLICIES(policy_id)
    ON DELETE CASCADE,

    CONSTRAINT unique_policy_permission_snapshot
    UNIQUE (policy_id, action_type)
    );